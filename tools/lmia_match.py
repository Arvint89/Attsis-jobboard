"""lmia_match.py -- JB-15: mark registry companies that were issued positive LMIAs.

  python tools/lmia_match.py                # download the latest quarters, write the report
  python tools/lmia_match.py --apply        # also write `lmia` into engine/companies.json
  python tools/lmia_match.py --quarters 4

Source: ESDC "Temporary Foreign Worker Program (TFWP): Positive Labour Market Impact Assessment
(LMIA) Employers List" on open.canada.ca (one XLSX per quarter; employer, address, NOC, positions).

What it means on the board: the employer was issued positive LMIAs in those quarters, i.e. it has
hired foreign workers through the TFWP. It is NOT a promise that a given role is sponsored, so the
facet value is "lmia" (chip "LMIA employer"), not "yes" -- and a JD that says "no sponsorship" wins.

Matching is exact on a normalized name (legal suffixes dropped). When the LMIA address doesn't
contain the registry city, the match is kept but flagged in the report for review.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import io
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
DATASET = "90fed587-1364-4f33-a9ee-208181dc0b97"
SOURCE = "ESDC TFWP positive LMIA employers (open.canada.ca)"
_LEGAL = {"inc", "ltd", "limited", "corp", "corporation", "co", "company", "incorporated", "ltee",
          "llc", "ulc", "the", "canada"}


def norm(name: str) -> str:
    import unicodedata
    s = "".join(c for c in unicodedata.normalize("NFKD", name or "") if not unicodedata.combining(c))
    return " ".join(w for w in re.findall(r"[a-z0-9]+", s.lower().replace("&", " and ")) if w not in _LEGAL)


def _fold(s: str) -> str:
    import unicodedata
    return "".join(c for c in unicodedata.normalize("NFKD", s or "") if not unicodedata.combining(c)).lower()


def match(rows_by_quarter: dict, registry: list) -> dict:
    """rows_by_quarter: {"2026Q1": [(prov, stream, employer, address, occupation, status, lmias, positions), ...]}"""
    want = {}
    for c in registry:
        n = norm(c.get("name"))
        if n:
            want[n] = c
    out = {}
    for q in sorted(rows_by_quarter):
        for r in rows_by_quarter[q]:
            if not r or len(r) < 8 or not r[2]:
                continue
            c = want.get(norm(str(r[2])))
            if not c:
                continue
            m = out.setdefault(c["name"], {"quarters": [], "positions": 0, "nocs": {}, "city_check": "ok"})
            if q not in m["quarters"]:
                m["quarters"].append(q)
            try:
                m["positions"] += int(r[7] or 0)
            except (TypeError, ValueError):
                pass
            noc = str(r[4] or "").split("-")[0].strip()
            if noc:
                m["nocs"][noc] = m["nocs"].get(noc, 0) + 1
            city = (c.get("city") or "").strip()
            addr = re.sub(r"\s+", " ", str(r[3] or "")).strip()
            if city and _fold(city.split()[0]) not in _fold(addr) and m["city_check"] == "ok":
                m["city_check"] = addr
    for m in out.values():
        m["quarters"].sort()
    return out


def _download(n_quarters: int) -> dict:
    import openpyxl
    import requests
    pkg = requests.get("https://open.canada.ca/data/api/action/package_show", params={"id": DATASET},
                       timeout=60).json()["result"]

    def name(x):
        v = x.get("name")
        return (v.get("en") if isinstance(v, dict) else v) or ""

    en = [x for x in pkg["resources"] if "en" in (x.get("language") or []) and
          (x.get("format") or "").upper() == "XLSX" and re.match(r"\d{4}Q\d", name(x))]
    en.sort(key=lambda x: name(x)[:6])
    out = {}
    for x in en[-n_quarters:]:
        q = name(x)[:6]
        data = requests.get(x["url"], timeout=180).content
        ws = openpyxl.load_workbook(io.BytesIO(data), read_only=True).worksheets[0]
        out[q] = [r for r in ws.iter_rows(min_row=3, values_only=True)]
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--quarters", type=int, default=4)
    a = ap.parse_args(argv)
    reg_path = os.path.join(ROOT, "engine", "companies.json")
    reg = json.load(open(reg_path, encoding="utf-8"))
    regl = reg if isinstance(reg, list) else reg["companies"]
    rows = _download(a.quarters)
    m = match(rows, regl)
    qs = sorted(rows)
    today = _dt.date.today().isoformat()
    lines = [f"# LMIA employer match — {today}", "",
             f"Source: {SOURCE}, quarters {qs[0]}–{qs[-1]} ({sum(len(v) for v in rows.values())} rows). "
             "Generated by `tools/lmia_match.py` (JB-15). Exact normalized-name match.", "",
             f"**{len(m)} of {len(regl)} registry companies** were issued positive LMIAs in these quarters.", "",
             "| Company | Quarters | Positions | Top NOC codes | Address check |", "|---|---|---|---|---|"]
    for k, v in sorted(m.items(), key=lambda kv: -kv[1]["positions"]):
        nocs = ", ".join(n for n, _ in sorted(v["nocs"].items(), key=lambda x: -x[1])[:3])
        chk = "✅ city matches" if v["city_check"] == "ok" else f"⚠️ review: `{v['city_check']}`"
        lines.append(f"| {k} | {', '.join(v['quarters'])} | {v['positions']} | {nocs} | {chk} |")
    os.makedirs(os.path.join(ROOT, "docs", "status"), exist_ok=True)
    out = os.path.join(ROOT, "docs", "status", f"LMIA_{today}.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(m)} matched -> {out}")
    if a.apply:
        for c in regl:
            v = m.get(c["name"])
            if v:
                c["lmia"] = {"quarters": v["quarters"], "positions": v["positions"], "source": SOURCE}
            else:
                c.pop("lmia", None)          # refresh: drop employers no longer in the window
        with open(reg_path, "w", encoding="utf-8", newline="") as f:
            json.dump(reg, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"wrote lmia on {len(m)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
